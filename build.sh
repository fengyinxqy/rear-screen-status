#!/usr/bin/env bash
# Build the rear-screen status app without Gradle: aapt2 -> javac -> d8 -> jar -> zipalign -> apksigner.
# Needs a JDK plus the toolchain under .toolchain/ (build-tools 36, android-36 platform, Shizuku AARs).
# aapt2 on Windows only accepts native paths, so every path it sees goes through cygpath.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TC="$ROOT/.toolchain"
BT="$TC/sdk/build-tools/android-16"
ANDROID_JAR="$TC/sdk/platforms/android-36/android.jar"
AAR="$TC/sdk/aar"
OUT="$ROOT/build/source"
APP="$ROOT/app"

W() { cygpath -w "$1"; }

# One source of truth for the version. The APK's versionCode and the Shizuku user service's
# version must match or a stale helper process keeps running the old shell code with no error
# anywhere; Version.java is generated here so they cannot drift.
VERSION_CODE="${VERSION_CODE:-46}"
VERSION_NAME="${VERSION_NAME:-4.10}"
[ -f "$ANDROID_JAR" ] || { echo "missing android.jar at $ANDROID_JAR" >&2; exit 1; }

rm -rf "$OUT"
mkdir -p "$OUT/gen" "$OUT/classes" "$OUT/dex" "$OUT/compile"

mkdir -p "$OUT/gen/com/dsh/rearscreen"
printf 'package com.dsh.rearscreen;\n\n/** Generated by build.sh. Do not edit. */\npublic final class Version {\n    public static final int CODE = %s;\n\n    private Version() { }\n}\n' \
  "$VERSION_CODE" > "$OUT/gen/com/dsh/rearscreen/Version.java"

echo "== aapt2 compile"
find "$APP/res" -type f | while IFS= read -r f; do
  "$BT/aapt2.exe" compile -o "$(W "$OUT/compile")" "$(W "$f")"
done

echo "== aapt2 link"
FLATS=""
for f in "$OUT"/compile/*.flat; do FLATS="$FLATS \"$(W "$f")\""; done
eval "\"$BT/aapt2.exe\" link \
  -I \"$(W "$ANDROID_JAR")\" \
  --manifest \"$(W "$APP/AndroidManifest.xml")\" \
  --java \"$(W "$OUT/gen")\" \
  --min-sdk-version 30 --target-sdk-version 36 \
  --version-code "$VERSION_CODE" --version-name "$VERSION_NAME" \
  -o \"$(W "$OUT/base.apk")\" $FLATS"

echo "== javac"
CPW="$(W "$ANDROID_JAR");$(W "$AAR/api/classes.jar");$(W "$AAR/provider/classes.jar");$(W "$AAR/aidl/classes.jar");$(W "$AAR/shared/classes.jar")"
SOURCESW=""
while IFS= read -r f; do [[ "$f" == */app/src/com/dsh/rearscreen/Version.java ]] && continue; SOURCESW="$SOURCESW \"$(W "$f")\""; done < <(find "$APP/src" "$OUT/gen" -name '*.java' ! -path "$APP/src/com/dsh/rearscreen/Version.java")
eval "javac -encoding UTF-8 -classpath \"$CPW\" -d \"$(W "$OUT/classes")\" $SOURCESW"
[ -f "$OUT/classes/com/dsh/rearscreen/MainActivity.class" ] || { echo "compile produced nothing" >&2; exit 1; }

echo "== d8"
DEXCLASSES=$(find "$OUT/classes" -name '*.class' | tr '\n' ' ')
"$BT/d8.exe" --release --min-api 30 --lib "$(W "$ANDROID_JAR")" --output "$(W "$OUT/dex")" \
  $DEXCLASSES \
  "$(W "$AAR/api/classes.jar")" "$(W "$AAR/provider/classes.jar")" \
  "$(W "$AAR/aidl/classes.jar")" "$(W "$AAR/shared/classes.jar")"

echo "== package"
cp "$OUT/base.apk" "$OUT/app.apk"
(cd "$OUT/dex" && jar uf "$(W "$OUT/app.apk")" classes.dex)

echo "== zipalign"
"$BT/zipalign.exe" -f -p 4 "$(W "$OUT/app.apk")" "$(W "$OUT/app-aligned.apk")"

echo "Unsigned APK: $OUT/app-aligned.apk"
